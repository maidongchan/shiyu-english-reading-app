function parseRoute() {
  const raw = window.location.hash.replace(/^#\/?/, "");
  const [route, id] = raw.split("/");
  if (["discover", "packs", "study", "article"].includes(route)) {
    return { route, id: id || null };
  }
  return { route: "discover", id: null };
}

function syncRoute(options = {}) {
  const next = parseRoute();
  const changedArticle = next.route === "article" && next.id !== state.articleId;
  const changedStudy =
    next.route === "study" &&
    next.id &&
    (state.route !== "study" || state.study.packId !== next.id);

  state.route = next.route;
  state.articleId = next.route === "article" ? next.id : null;

  if (changedArticle) {
    state.collection = [];
    state.activeWord = null;
    state.wordSheetOpen = false;
    state.showTranslation = false;
    state.selectedPackId = state.packs[0]?.id || null;
  }

  if (changedStudy) {
    state.study = {
      packId: next.id,
      index: 0,
      revealed: false,
      known: 0,
      again: 0
    };
  }

  if (next.route === "study" && !next.id && state.packs[0]) {
    window.history.replaceState(null, "", `#study/${state.packs[0].id}`);
    syncRoute(options);
    return;
  }

  if (!options.keepOverlay) {
    state.modal = null;
    state.packModalContext = null;
  }
}

function navigate(route, id = null) {
  const nextHash = id ? `#${route}/${id}` : `#${route}`;
  state.modal = null;
  state.packModalContext = null;
  state.wordSheetOpen = false;
  if (window.location.hash === nextHash) {
    syncRoute();
    render();
  } else {
    window.location.hash = nextHash;
  }
}


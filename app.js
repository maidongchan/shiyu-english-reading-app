function renderWordTokens(paragraph) {
  const tokens = paragraph.split(/(\b[A-Za-z]+(?:['’-][A-Za-z]+)?\b)/g);
  return tokens
    .map((token) => {
      if (!/^[A-Za-z]+(?:['’-][A-Za-z]+)?$/.test(token)) return esc(token);
      const normalized = normalizeWord(token);
      const classes = ["word-token"];
      if (state.activeWord === normalized && state.wordSheetOpen) classes.push("active");
      else if (state.activeWord === normalized) classes.push("active");
      if (state.collection.includes(normalized)) classes.push("collected");
      if (isWordSaved(normalized)) classes.push("saved");
      return `<button class="${classes.join(" ")}" type="button" data-word="${esc(normalized)}">${esc(token)}</button>`;
    })
    .join("");
}

function normalizeWord(word) {
  return String(word).toLowerCase().replace(/[’]/g, "'").trim();
}

function isWordSaved(word) {
  return state.packs.some((pack) =>
    pack.words.some((entry) => normalizeWord(entry.word) === normalizeWord(word))
  );
}

function wordDetails(word, article = articleById(state.articleId)) {
  const normalized = normalizeWord(word);
  let entry = DICTIONARY[normalized];
  if (normalized === "fungal") entry = FUNGAL_ENTRY;
  if (!entry) {
    const sourceSentence = findSentence(normalized, article);
    entry = {
      phonetic: `/${normalized}/`,
      pos: "word",
      meaning: "待补充释义",
      definition: "这个词还未收录在原型词典中，可以先加入词包继续学习。",
      example: sourceSentence || `“${word}” appears in this article.`
    };
  }
  return {
    word: normalized,
    ...entry,
    source: article?.title || "文章拾词"
  };
}

function findSentence(word, article) {
  if (!article) return "";
  const pattern = new RegExp(`\\b${word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "i");
  for (const paragraph of article.paragraphs || []) {
    if (!pattern.test(paragraph)) continue;
    return (
      paragraph
        .split(/(?<=[.!?])\s+/)
        .find((sentence) => pattern.test(sentence)) || paragraph
    );
  }
  return "";
}


function openArticle(id) {
  if (!articleById(id)) return;
  navigate("article", id);
}

function selectWord(word) {
  const normalized = normalizeWord(word);
  if (!state.collection.includes(normalized)) state.collection.push(normalized);
  state.activeWord = normalized;
  state.wordSheetOpen = true;
  if (!state.selectedPackId) state.selectedPackId = state.packs[0]?.id || null;
  render({ preserveScroll: true });
}

function saveActiveWord() {
  const pack = packById(state.selectedPackId);
  if (!pack || !state.activeWord) return;
  if (pack.words.some((entry) => normalizeWord(entry.word) === state.activeWord)) {
    showToast("这个词已经在词包里了");
    return;
  }
  const article = articleById(state.articleId);
  const details = wordDetails(state.activeWord, article);
  pack.words.push({
    ...details,
    mastered: false,
    addedAt: Date.now()
  });
  savePacks();
  state.wordSheetOpen = false;
  render({ preserveScroll: true });
  showToast(`已加入「${pack.name}」`);
}

function startStudy(packId) {
  if (!packById(packId)) return;
  navigate("study", packId);
}

function currentStudyPack() {
  return packById(state.study.packId);
}

function currentStudyWord() {
  const pack = currentStudyPack();
  return pack?.words[state.study.index] || null;
}

function revealStudyCard() {
  state.study.revealed = true;
  render();
}

function advanceStudy(known) {
  const pack = currentStudyPack();
  const word = currentStudyWord();
  if (!pack || !word) return;
  word.mastered = known;
  pack.lastStudied = "刚刚";
  if (known) state.study.known += 1;
  else state.study.again += 1;
  state.study.index += 1;
  state.study.revealed = false;
  savePacks();
  render();
}

function restartStudy() {
  state.study.index = 0;
  state.study.revealed = false;
  state.study.known = 0;
  state.study.again = 0;
  render();
}

function openUpload() {
  state.modal = "upload";
  state.packModalContext = null;
  state.wordSheetOpen = false;
  renderOverlay();
}

function openCreatePack() {
  state.packModalContext =
    state.wordSheetOpen && state.activeWord
      ? {
          word: state.activeWord,
          source: articleById(state.articleId)?.title || "文章拾词"
        }
      : null;
  state.modal = "create-pack";
  state.wordSheetOpen = false;
  renderOverlay();
}

function closeModal() {
  state.modal = null;
  state.packModalContext = null;
  renderOverlay();
}

function createPack(form) {
  const data = new FormData(form);
  const name = String(data.get("name") || "").trim();
  if (!name) return;
  const id = `pack-${Date.now()}`;
  const pack = {
    id,
    name,
    description: String(data.get("description") || "").trim() || "从阅读中收集的个人词包",
    color: String(data.get("color") || "#2f6b4a"),
    lastStudied: "尚未学习",
    words: []
  };

  if (state.packModalContext?.word) {
    pack.words.push({
      ...wordDetails(state.packModalContext.word, articleById(state.articleId)),
      source: state.packModalContext.source,
      mastered: false,
      addedAt: Date.now()
    });
  }

  state.packs.push(pack);
  state.selectedPackId = id;
  savePacks();
  state.modal = null;
  state.packModalContext = null;
  state.wordSheetOpen = false;
  render({ preserveScroll: true });
  showToast(`词包「${name}」已创建`);
}

function publishArticle(form) {
  const data = new FormData(form);
  const title = String(data.get("title") || "").trim();
  const body = String(data.get("body") || "").trim();
  if (!title || !body) return;
  const source = String(data.get("source") || "").trim() || "Lin";
  const category = String(data.get("category") || "文化");
  const level = String(data.get("level") || "B1");
  const paragraphs = body
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.replace(/\s+/g, " ").trim())
    .filter(Boolean);
  const words = body.match(/\b[A-Za-z]+\b/g) || [];
  const imageMap = {
    自然: "./assets/forest.jpg",
    城市: "./assets/city.jpg",
    心理: "./assets/music.jpg",
    文化: "./assets/books.jpg"
  };
  const article = {
    id: `community-${Date.now()}`,
    title,
    subtitle: "来自社区读者的英文分享。",
    category,
    level,
    readTime: Math.max(3, Math.ceil(words.length / 170)),
    readers: 1,
    date: "刚刚",
    author: { name: source, initials: iconInitials(source) },
    image: imageMap[category] || "./assets/books.jpg",
    excerpt: paragraphs[0].slice(0, 180),
    paragraphs,
    translations: []
  };
  state.uploads.unshift(article);
  saveUploads();
  state.modal = null;
  navigate("article", article.id);
  showToast("文章已发布到社区");
}


function showToast(message) {
  clearTimeout(state.toastTimer);
  toastRoot.innerHTML = `<div class="toast">${esc(message)}</div>`;
  state.toastTimer = window.setTimeout(() => {
    toastRoot.innerHTML = "";
  }, 2400);
}

function speak(text) {
  if (!text) return;
  if (!("speechSynthesis" in window)) {
    showToast("当前浏览器暂不支持朗读");
    return;
  }
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = "en-US";
  utterance.rate = 0.88;
  window.speechSynthesis.cancel();
  window.speechSynthesis.speak(utterance);
}

function handleClick(event) {
  const routeTarget = event.target.closest("[data-route]");
  if (routeTarget) {
    navigate(routeTarget.dataset.route);
    return;
  }

  const wordTarget = event.target.closest("[data-word]");
  if (wordTarget) {
    selectWord(wordTarget.dataset.word);
    return;
  }

  const articleTarget = event.target.closest("[data-open-article]");
  if (articleTarget) {
    openArticle(articleTarget.dataset.openArticle);
    return;
  }

  const actionTarget = event.target.closest("[data-action]");
  if (!actionTarget) return;
  const action = actionTarget.dataset.action;

  if (action === "open-upload") openUpload();
  else if (action === "close-modal") closeModal();
  else if (action === "open-create-pack") openCreatePack();
  else if (action === "clear-search") clearSearch();
  else if (action === "reset-feed") resetFeed();
  else if (action === "set-filter") setFilter(actionTarget.dataset.filter);
  else if (action === "go-back") goBack();
  else if (action === "bookmark-article") showToast("文章已收藏");
  else if (action === "share-article") showToast("分享链接已准备好");
  else if (action === "toggle-translation") {
    state.showTranslation = !state.showTranslation;
    render({ preserveScroll: true });
  } else if (action === "open-collection") {
    if (state.collection.length) {
      state.activeWord = state.collection[0];
      state.wordSheetOpen = true;
      renderOverlay();
    } else {
      showToast("先在文章里点一个单词吧");
    }
  } else if (action === "close-word-sheet") {
    state.wordSheetOpen = false;
    renderOverlay();
    renderView();
  } else if (action === "select-pack") {
    state.selectedPackId = actionTarget.dataset.packId;
    renderOverlay();
  } else if (action === "select-collected-word") {
    state.activeWord = normalizeWord(actionTarget.dataset.word);
    renderOverlay();
  } else if (action === "save-active-word") {
    saveActiveWord();
  } else if (action === "start-study") {
    startStudy(actionTarget.dataset.packId);
  } else if (action === "speak-word") {
    speak(actionTarget.dataset.word);
  } else if (action === "speak-current") {
    speak(currentStudyWord()?.word);
  } else if (action === "reveal-card") {
    revealStudyCard();
  } else if (action === "study-again") {
    advanceStudy(false);
  } else if (action === "study-know") {
    advanceStudy(true);
  } else if (action === "restart-study") {
    restartStudy();
  } else if (action === "back-to-packs") {
    navigate("packs");
  }
}

function handleSubmit(event) {
  if (event.target.id === "create-pack-form") {
    event.preventDefault();
    createPack(event.target);
  } else if (event.target.id === "upload-form") {
    event.preventDefault();
    publishArticle(event.target);
  }
}

function handleInput(event) {
  if (event.target.id === "home-search") {
    updateSearch(event.target.value);
  } else if (event.target.matches('#upload-form textarea[name="body"]')) {
    const count = document.querySelector("#body-count");
    if (count) {
      const chars = event.target.value.length;
      const words = (event.target.value.match(/\b[A-Za-z]+\b/g) || []).length;
      count.textContent = `${chars} 个字符 · 约 ${words} 个英文词`;
    }
  }
}

document.addEventListener("click", handleClick);
document.addEventListener("submit", handleSubmit);
document.addEventListener("input", handleInput);

window.addEventListener("hashchange", () => {
  syncRoute();
  render();
});

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    if (state.modal) closeModal();
    else if (state.wordSheetOpen) {
      state.wordSheetOpen = false;
      renderOverlay();
      renderView();
    }
  }
  if (state.route === "study" && !state.modal) {
    if (event.code === "Space") {
      event.preventDefault();
      if (!state.study.revealed) revealStudyCard();
    }
    if (state.study.revealed && event.key === "ArrowRight") advanceStudy(true);
    if (state.study.revealed && event.key === "ArrowLeft") advanceStudy(false);
  }
});

if (!window.location.hash) {
  window.history.replaceState(null, "", "#discover");
}
syncRoute();
render();
